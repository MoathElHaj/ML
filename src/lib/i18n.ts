export const locales = ["ar", "en"] as const;
export type Lang = (typeof locales)[number];
export const defaultLang: Lang = "ar";

export function isLang(value: string): value is Lang {
  return (locales as readonly string[]).includes(value);
}

export const dirOf = (lang: Lang) => (lang === "ar" ? "rtl" : "ltr");

/** Public URL for a path in a language: Arabic has no prefix, English lives under /en. */
export function href(lang: Lang, path: string) {
  if (lang === "ar") return path;
  return path === "/" ? "/en" : `/en${path}`;
}

/** Strips a leading /ar or /en so both rewritten and browser paths compare the same. */
export function basePath(pathname: string) {
  const stripped = pathname.replace(/^\/(ar|en)(?=\/|$)/, "");
  return stripped === "" ? "/" : stripped;
}

/** Picks the English value when the visitor reads English and one exists, else the Arabic value. */
export function pick<T>(lang: Lang, ar: T, en: T | null | undefined): T {
  if (lang === "en" && en !== null && en !== undefined && (typeof en !== "string" || en.trim() !== "") && (!Array.isArray(en) || en.length > 0)) {
    return en;
  }
  return ar;
}

