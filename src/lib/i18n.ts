const dictionaries: Record<Lang, Dict> = { ar, en };

export function getDict(lang: Lang): Dict {
  return dictionaries[lang];
}

/** Reads `lang` from route params; the [lang] layout already 404s anything else. */
export async function langFrom(params: Promise<{ lang: string }>): Promise<Lang> {
  const { lang } = await params;
  return isLang(lang) ? lang : defaultLang;
}
